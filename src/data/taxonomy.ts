/* ------------------------------------------------------------------ *
 * PVF taxonomy (Pipe, Valves & Fittings).
 *
 * The class is what makes enrichment bounded. Once a SKU is classified,
 * its class dictates exactly which attributes must exist, what units they
 * carry and which values are legal - so extraction becomes "fill this
 * schema" rather than "find whatever you can", and completeness becomes
 * something you can actually measure.
 * ------------------------------------------------------------------ */

import type { AttributeSpec, TaxonomyClass } from "@/lib/types";

type SpecInput = Partial<AttributeSpec> &
  Pick<AttributeSpec, "key" | "label" | "group" | "type" | "description">;

function spec(input: SpecInput): AttributeSpec {
  return {
    required: false,
    facetable: false,
    searchWeight: 0.3,
    ...input,
  };
}


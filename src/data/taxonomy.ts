export const TAXONOMY_BY_ID = new Map(TAXONOMY.map((t) => [t.id, t]));

export function getClass(id: string): TaxonomyClass {
  const found = TAXONOMY_BY_ID.get(id);
  if (!found) throw new Error(`Unknown taxonomy class: ${id}`);
  return found;
}

export function getSpec(
  cls: TaxonomyClass,
  key: string,
): AttributeSpec | undefined {
  return cls.attributes.find((a) => a.key === key);
}
